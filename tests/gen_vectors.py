#!/usr/bin/env python3
"""Generate tests/vectors.h from independent reference implementations
(pyca/cryptography, libsodium via PyNaCl, hashlib/hmac).  Run with:
    python3 tests/gen_vectors.py > tests/vectors.h
The RFC vectors are hard-coded in crypto_test.c; these add breadth
(many lengths, chunk boundaries) and a second, independent oracle."""
import hashlib, hmac
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms
import nacl.bindings as nb
import nacl.signing

def det(n, seed):
    out = b""; c = 0
    while len(out) < n:
        out += hashlib.sha256(seed + c.to_bytes(4, "little")).digest(); c += 1
    return out[:n]

def c(b): return "{" + ",".join("0x%02x" % x for x in b) + "}" if b else "{0}"

LENS = [0, 1, 15, 16, 17, 63, 64, 65, 127, 128, 129, 300, 1000]
print("/* generated by tests/gen_vectors.py - do not edit */")
print("typedef struct { unsigned len; const unsigned char *msg; const unsigned char sha256[32]; const unsigned char sha512[64]; } hash_vec_t;")
for i, n in enumerate(LENS):
    m = det(n, b"msg%d" % i)
    print("static const unsigned char hmsg%d[] = %s;" % (i, c(m)))
print("static const hash_vec_t hash_vecs[] = {")
for i, n in enumerate(LENS):
    m = det(n, b"msg%d" % i)
    print("  {%d, hmsg%d, %s, %s}," % (n, i, c(hashlib.sha256(m).digest()), c(hashlib.sha512(m).digest())))
print("};")

print("typedef struct { unsigned klen, mlen; const unsigned char *key, *msg; const unsigned char mac[32]; } hmac_vec_t;")
HM = [(0, 0), (16, 3), (32, 64), (64, 100), (65, 17), (200, 300)]
for i, (kl, ml) in enumerate(HM):
    print("static const unsigned char hmk%d[] = %s;" % (i, c(det(kl, b"hk%d" % i))))
    print("static const unsigned char hmm%d[] = %s;" % (i, c(det(ml, b"hm%d" % i))))
print("static const hmac_vec_t hmac_vecs[] = {")
for i, (kl, ml) in enumerate(HM):
    k, m = det(kl, b"hk%d" % i), det(ml, b"hm%d" % i)
    print("  {%d, %d, hmk%d, hmm%d, %s}," % (kl, ml, i, i, c(hmac.new(k, m, hashlib.sha256).digest())))
print("};")

print("typedef struct { unsigned slen, ilen, olen; const unsigned char *salt, *ikm, *info, *okm; } hkdf_vec_t;")
HK = [(0, 0, 32), (13, 10, 42), (32, 40, 82), (80, 80, 255)]
for i, (sl, il, ol) in enumerate(HK):
    salt, ikm, info = det(sl, b"hs%d" % i), det(22 + i * 10, b"hi%d" % i), det(il, b"hn%d" % i)
    okm = HKDF(algorithm=hashes.SHA256(), length=ol, salt=salt or None, info=info).derive(ikm)
    print("static const unsigned char hks%d[] = %s;" % (i, c(salt)))
    print("static const unsigned char hki%d[] = %s;" % (i, c(ikm)))
    print("static const unsigned char hkn%d[] = %s;" % (i, c(info)))
    print("static const unsigned char hko%d[] = %s;" % (i, c(okm)))
print("static const hkdf_vec_t hkdf_vecs[] = {")
for i, (sl, il, ol) in enumerate(HK):
    print("  {%d, %d, %d, hks%d, hki%d, hkn%d, hko%d}," % (sl, il, ol, i, i, i, i))
print("};")
print("static const unsigned hkdf_ikm_len[] = {%s};" % ",".join(str(22 + i * 10) for i in range(len(HK))))

print("typedef struct { unsigned alen, mlen; const unsigned char key[32], nonce[24]; const unsigned char *aad, *pt, *ct; const unsigned char tag[16]; } aead_vec_t;")
AL = [(0, 0), (0, 1), (12, 64), (16, 65), (33, 300), (1, 1000)]
for kind in ("ietf", "x"):
    for i, (al, ml) in enumerate(AL):
        key, aad, pt = det(32, b"k%s%d" % (kind.encode(), i)), det(al, b"a%d" % i), det(ml, b"p%d" % i)
        nonce = det(12 if kind == "ietf" else 24, b"n%s%d" % (kind.encode(), i))
        if kind == "ietf":
            out = ChaCha20Poly1305(key).encrypt(nonce, pt, aad or None)
        else:
            out = nb.crypto_aead_xchacha20poly1305_ietf_encrypt(pt, aad or None, nonce, key)
        print("static const unsigned char %sa%d[] = %s;" % (kind, i, c(aad)))
        print("static const unsigned char %sp%d[] = %s;" % (kind, i, c(pt)))
        print("static const unsigned char %sc%d[] = %s;" % (kind, i, c(out[:-16])))
    print("static const aead_vec_t %s_vecs[] = {" % kind)
    for i, (al, ml) in enumerate(AL):
        key = det(32, b"k%s%d" % (kind.encode(), i))
        nonce = det(12 if kind == "ietf" else 24, b"n%s%d" % (kind.encode(), i))
        pt, aad = det(ml, b"p%d" % i), det(al, b"a%d" % i)
        if kind == "ietf":
            out = ChaCha20Poly1305(key).encrypt(nonce, pt, aad or None)
        else:
            out = nb.crypto_aead_xchacha20poly1305_ietf_encrypt(pt, aad or None, nonce, key)
        print("  {%d, %d, %s, %s, %sa%d, %sp%d, %sc%d, %s}," % (al, ml, c(key), c(nonce), kind, i, kind, i, kind, i, c(out[-16:])))
    print("};")

print("typedef struct { unsigned mlen; const unsigned char seed[32], pk[32]; const unsigned char *msg; const unsigned char sig[64]; } ed_vec_t;")
EL = [0, 1, 2, 31, 32, 64, 200, 1023]
for i, ml in enumerate(EL):
    print("static const unsigned char edm%d[] = %s;" % (i, c(det(ml, b"em%d" % i))))
print("static const ed_vec_t ed_vecs[] = {")
for i, ml in enumerate(EL):
    seed, m = det(32, b"es%d" % i), det(ml, b"em%d" % i)
    sk = nacl.signing.SigningKey(seed)
    print("  {%d, %s, %s, edm%d, %s}," % (ml, c(seed), c(bytes(sk.verify_key)), i, c(sk.sign(m).signature)))
print("};")
